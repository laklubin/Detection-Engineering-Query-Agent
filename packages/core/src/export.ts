/**
 * Export rendering.
 *
 * Generated content is strictly read-only: these functions produce text for
 * the clipboard or a file download. Nothing here deploys a query, contacts a
 * SIEM, or executes anything.
 */

import {
  APP_NAME,
  COMMERCIAL_NOTICE,
  PLATFORMS,
  VALIDATION_DISCLAIMER,
  VALIDATION_STATUS_LABEL,
  type PlatformId,
} from './constants.js';
import { findLogSource, findVendor } from './catalog.js';
import type { GeneratedUseCase, GenerateResponse, PlatformQuery } from './schemas.js';
import { describeLogicalField } from './mappings/fields.js';

function bullet(items: readonly string[]): string {
  return items.length === 0 ? '_None recorded._' : items.map((i) => `- ${i}`).join('\n');
}

function commentPrefix(platform: PlatformId): string {
  switch (platform) {
    case 'qradar':
      return '--';
    case 'securonix':
      return '//';
    case 'fortisiem':
    case 'sigma':
      return '#';
    case 'splunk':
      return '```';
    default:
      return '//';
  }
}

/** Header stamped onto a single-platform query export. */
export function queryFileHeader(useCase: GeneratedUseCase, query: PlatformQuery, generatedAt: string): string {
  const p = commentPrefix(query.platform);
  const wrap = (line: string) => (query.platform === 'splunk' ? `\`\`\` ${line} \`\`\`` : `${p} ${line}`);
  const lines = [
    wrap(`${useCase.spec.name}`),
    wrap(`Use case id: ${useCase.useCaseId}`),
    wrap(`Platform: ${query.product} (${query.language})`),
    wrap(`Validation status: ${VALIDATION_STATUS_LABEL[query.status]}`),
    wrap(`Generated by ${APP_NAME} at ${generatedAt}`),
    wrap('Not executed against a live SIEM. Review before deployment.'),
  ];
  if (query.mappingGaps.length > 0) {
    lines.push(wrap(`Mapping required for: ${query.mappingGaps.map((g) => g.logical).join(', ')}`));
  }
  return lines.join('\n');
}

export function renderQueryFile(
  useCase: GeneratedUseCase,
  query: PlatformQuery,
  generatedAt: string,
): string {
  if (query.query === null) {
    return `${queryFileHeader(useCase, query, generatedAt)}\n\n${commentPrefix(query.platform)} This platform cannot express this detection as a standalone query.\n`;
  }
  return `${queryFileHeader(useCase, query, generatedAt)}\n\n${query.query}\n`;
}

/** Full detection-engineering document for one use case. */
export function renderUseCaseMarkdown(useCase: GeneratedUseCase, generatedAt: string): string {
  const { spec } = useCase;
  const vendor = findVendor(spec.vendorId);
  const sources = spec.logSourceIds.map((id) => findLogSource(id)?.name ?? id);
  const c = spec.correlation;

  const out: string[] = [];
  out.push(`# ${spec.name}`);
  out.push('');
  out.push(`**Use case ID:** \`${useCase.useCaseId}\`  `);
  out.push(`**Slug:** \`${spec.slug}\`  `);
  out.push(`**Severity recommendation:** ${spec.severity}  `);
  out.push(`**Overall validation status:** ${VALIDATION_STATUS_LABEL[useCase.overallStatus]}  `);
  out.push(`**Generated:** ${generatedAt}`);
  out.push('');
  out.push('## 1. Detection objective');
  out.push(spec.objective);
  out.push('');
  out.push('## 2. Attack scenario');
  out.push(spec.attackScenario);
  out.push('');
  out.push('## 3. Required vendor and log sources');
  out.push(`- **Vendor:** ${vendor?.name ?? spec.vendorId}`);
  out.push(`- **Log sources:** ${sources.join(', ')}`);
  out.push('');
  out.push('## 4. Required event fields and mapping assumptions');
  out.push('| Logical field | Meaning |');
  out.push('| --- | --- |');
  for (const field of spec.requiredEventFields) {
    const described = describeLogicalField(field);
    out.push(`| \`${field}\` | ${described?.description ?? 'Not in the field registry — mapping required.'} |`);
  }
  out.push('');
  out.push('**Mapping assumptions**');
  out.push(bullet(spec.mappingAssumptions));
  out.push('');
  out.push('## 5. MITRE ATT&CK');
  if (spec.mitre.length === 0) {
    out.push('_No ATT&CK mapping was provided for this use case._');
  } else {
    out.push('| Tactic | Technique ID | Technique |');
    out.push('| --- | --- | --- |');
    for (const m of spec.mitre) {
      out.push(`| ${m.tacticName}${m.tacticId ? ` (${m.tacticId})` : ''} | \`${m.techniqueId}\` | ${m.techniqueName} |`);
    }
  }
  out.push('');
  out.push('## 6. Detection logic and correlation conditions');
  spec.stages.forEach((stage, index) => {
    out.push(`### Stage ${index + 1} — ${stage.name} (\`${stage.id}\`)`);
    out.push(`${stage.description}`);
    out.push('');
    out.push(`- Telemetry family: \`${stage.telemetry}\``);
    out.push(`- Condition logic: match **${stage.conditionLogic === 'all' ? 'ALL' : 'ANY'}** of:`);
    for (const cond of stage.conditions) {
      const value =
        cond.value === undefined
          ? ''
          : Array.isArray(cond.value)
            ? ` [${cond.value.map((v) => String(v)).join(', ')}]`
            : ` \`${String(cond.value)}\``;
      out.push(`  - \`${cond.field}\` **${cond.operator}**${value}${cond.rationale ? ` — ${cond.rationale}` : ''}`);
    }
    out.push('');
  });
  out.push(`**Correlation:** ${c.type}`);
  out.push(`- ${c.description}`);
  out.push(`- Group by: ${c.groupBy.length > 0 ? c.groupBy.map((g) => `\`${g}\``).join(', ') : '_none_'}`);
  if (c.type === 'sequence') out.push(`- Ordered: ${c.ordered ? 'yes' : 'no'}`);
  out.push('');
  out.push('## 7. Time window and threshold');
  out.push(`- Correlation window: **${c.timeWindowSeconds} seconds**`);
  out.push(`- Event threshold: ${c.eventThreshold !== undefined ? `**${c.eventThreshold}**` : '_not applicable_'}`);
  out.push(
    `- Distinct-value threshold: ${
      c.distinctThreshold !== undefined ? `**${c.distinctThreshold}** on \`${c.thresholdField}\`` : '_not applicable_'
    }`,
  );
  out.push('');
  out.push('## 8. False-positive considerations');
  out.push(bullet(spec.falsePositives));
  out.push('');
  out.push('## 9. Tuning and whitelisting recommendations');
  out.push(bullet(spec.tuning));
  out.push('');
  out.push('## 10. Validation and test recommendations');
  out.push(bullet(spec.validationRecommendations));
  out.push('');
  out.push('## 11. Query output per platform');
  out.push('');
  out.push(`> ${VALIDATION_DISCLAIMER}`);
  out.push('');
  for (const query of useCase.queries) {
    const descriptor = PLATFORMS[query.platform];
    out.push(`### ${descriptor.product} — ${descriptor.language}`);
    out.push('');
    out.push(`**Validation status:** ${VALIDATION_STATUS_LABEL[query.status]}`);
    out.push('');
    if (query.query === null) {
      out.push('_This platform cannot express this detection as a standalone query._');
    } else {
      out.push('```' + (query.platform === 'sigma' ? 'yaml' : 'text'));
      out.push(query.query);
      out.push('```');
    }
    out.push('');
    if (query.mappingGaps.length > 0) {
      out.push('**Mapping required**');
      out.push(bullet(query.mappingGaps.map((g) => `\`${g.logical}\` — ${g.note}`)));
      out.push('');
    }
    if (query.validationMessages.length > 0) {
      out.push('**Validation messages**');
      out.push(bullet(query.validationMessages));
      out.push('');
    }
    if (query.requiresPlatformConfiguration && query.configurationGuidance.length > 0) {
      out.push('**Platform configuration required**');
      out.push(bullet(query.configurationGuidance));
      out.push('');
    }
    if (query.notes.length > 0) {
      out.push('**Notes**');
      out.push(bullet(query.notes));
      out.push('');
    }
  }
  return out.join('\n');
}

/** Complete export bundle for a generation response. */
export function renderBundleMarkdown(response: GenerateResponse): string {
  const out: string[] = [];
  out.push(`# ${APP_NAME} — detection export`);
  out.push('');
  out.push(`- **Request ID:** \`${response.requestId}\``);
  out.push(`- **Generated at:** ${response.generatedAt}`);
  out.push(`- **Generation mode:** ${response.mode === 'demo' ? 'DEMO (synthetic fixture, not model generated)' : 'live inference'}`);
  out.push(`- **Model:** ${response.model ?? 'n/a'}`);
  out.push(`- **System prompt version:** ${response.promptVersion}`);
  out.push(`- **Use cases:** ${response.useCases.length}`);
  out.push('');
  out.push(`> ${VALIDATION_DISCLAIMER}`);
  out.push('');
  if (response.warnings.length > 0) {
    out.push('## Warnings');
    out.push(bullet(response.warnings));
    out.push('');
  }
  for (const useCase of response.useCases) {
    out.push('---');
    out.push('');
    out.push(renderUseCaseMarkdown(useCase, response.generatedAt));
    out.push('');
  }
  out.push('---');
  out.push('');
  out.push(`_${COMMERCIAL_NOTICE}_`);
  out.push('');
  return out.join('\n');
}

/** Machine-readable export. Identical data, stable shape. */
export function renderBundleJson(response: GenerateResponse): string {
  return JSON.stringify(
    {
      application: APP_NAME,
      requestId: response.requestId,
      generatedAt: response.generatedAt,
      mode: response.mode,
      model: response.model,
      promptVersion: response.promptVersion,
      validationDisclaimer: response.validationDisclaimer,
      commercialNotice: response.commercialNotice,
      warnings: response.warnings,
      useCases: response.useCases,
    },
    null,
    2,
  );
}

const SAFE_NAME = /[^a-z0-9._-]+/gi;

export function exportFilename(parts: readonly string[], extension: string): string {
  const stem = parts
    .map((p) =>
      p
        // Anything outside the safe set becomes a dash.
        .replace(SAFE_NAME, '-')
        // Collapse dot/dash runs so traversal sequences cannot survive.
        .replace(/[.-]{2,}/g, '-')
        .replace(/^[.-]+|[.-]+$/g, '')
        .toLowerCase(),
    )
    .filter((p) => p.length > 0)
    .join('_')
    .slice(0, 120);
  return `${stem || 'detectionforge-export'}.${extension.replace(SAFE_NAME, '')}`;
}

export function platformFileExtension(platform: PlatformId): string {
  return PLATFORMS[platform].fileExtension;
}
